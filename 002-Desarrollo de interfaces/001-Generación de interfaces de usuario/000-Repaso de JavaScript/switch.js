const opcion = "guardar";

switch (opcion) {

    case "guardar":

        console.log("Guardando datos...");

        break;


    case "eliminar":

        console.log("Eliminando datos...");

        break;


    case "cancelar":

        console.log("Operación cancelada");

        break;


    default:

        console.log("Opción desconocida");

}